"""A form that draws a complete-looking submission its route refuses.

`MobileField.required` was set from `type_ == 'path'` alone, so **no body field was ever marked
required** and every form drew every question as optional. Two consequences, and they are different
defects wearing one flag:

* the fields a route *does* require were drawn as optional, so a form offered a submission the route
  refused for a reason the person could not see coming. This one is a value correction — the route's
  own requirement set is already authoritative, and `afya.access.forms.required_fields` already
  computes it for §ACC-001;
* a route that refuses a *combination* of answers — a voice report with no recording, a lab with no
  turnaround — could not state the combination at all, because one boolean has no room for it. This
  one is a dependency, and it is what `MobileField.condition` carries.

Both are §11.1's "a control the server refuses" read at the form: the person is shown a screen that
says the submission is complete and the server disagrees.

The gates below read the **served** catalogue (`GET /mobile/actions`), not `catalogue()`, because
what a client parses is the served document — the same reason `test_action_reachability.py` reads
routes rather than restating them.
"""
import secrets

import httpx

from afya.access.forms import required_fields
from afya.auth.views import s256
from afya.mobile.actions import catalogue
from afya.service import build_services, create_app


def _full() -> list[dict]:
	"""The whole catalogue as a client would receive it, with `required` marked from the routes.

	`available()` filters this by dormancy and by the caller's scopes, so an endpoint read sees only
	what one caller may see — and two of the four conditional sites are Tier-4 dormant, one of them
	behind an operator scope. The marking is a pure function of the catalogue and the routes, so it
	is applied to the whole catalogue here; the endpoint's agreement with it is checked separately,
	on the subset the endpoint serves.
	"""
	app = create_app(build_services())
	from afya.mobile.actions import catalogue, marked
	return [a.model_dump(mode='json') for a in marked(catalogue(), required_fields(app))]


def _simplified() -> list[dict]:
	app = create_app(build_services())
	from afya.mobile.actions import catalogue, marked
	from afya.access.forms import simplified
	required = required_fields(app)
	return [a.model_dump(mode='json') for a in simplified(marked(catalogue(), required), required)]


def _document_required(app: object) -> dict[tuple[str, str], set[str]]:
	"""What each route requires, read off its **OpenAPI document** — an independent second reader.

	`required_fields()` walks the signatures, and a signature does not spell every requirement the
	way a reader expects: `Body(...)`/`Form(...)` markers are not `inspect.Parameter.empty`, so a
	parameter that FastAPI will refuse without is invisible to a `default is empty` test. Comparing
	`marked()`'s output to `required_fields()`'s output — which is what this gate did first — compares
	a reader to itself and can never fail. The document is generated by FastAPI from the same routes
	by a different path, so the two disagreeing is a fact about one of them.
	"""
	spec = app.openapi()  # type: ignore[attr-defined]
	out: dict[tuple[str, str], set[str]] = {}
	for path, ops in spec['paths'].items():
		for method, op in ops.items():
			names: set[str] = {p['name'] for p in op.get('parameters', [])
			                   if p.get('in') in ('query', 'path') and p.get('required')}
			body = op.get('requestBody')
			if body:
				for media in body.get('content', {}).values():
					schema = media.get('schema', {})
					ref = schema.get('$ref')
					if ref:
						schema = spec['components']['schemas'][ref.rsplit('/', 1)[1]]
					names |= set(schema.get('required', []))
			out[(method.upper(), path)] = names
	return out


async def test_the_endpoint_serves_what_the_marking_produces() -> None:
	"""The route applies the marking, and this is what says so.

	Everything below reads the pure functions, which would pass even if `service.py` forgot to call
	`marked()` — the defect would be a form that ships unmarked while every gate stayed green. So the
	served document is compared to the marking directly, field for field, on the subset it serves.
	"""
	app = create_app(build_services())
	async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url='http://t') as c:
		resp = await c.get('/mobile/actions')
		assert resp.status_code == 200, resp.text
		served = resp.json()
	assert served, 'the endpoint served nothing, so this gate would pass vacuously'

	# The route's own requirement set, read independently of the reader `marked()` uses — a comparison
	# against `required_fields()` would compare the marking to the thing it was computed from.
	needed = _document_required(app)
	# A client-supplied subject is required by the route and undrawn by the form, and the form is
	# right not to draw it: the client injects its own. The marking still marks it, because the flag
	# is a fact about the route — the *drawing* is what `client_supplied` decides. So the comparison
	# keeps it, and the served document must agree about it too.
	disagree: list[str] = []
	for act in served:
		req = needed.get((act['method'], act['path']), set())
		for fld in act['fields']:
			want = fld['name'] in req and fld.get('condition') is None
			if fld['required'] != want:
				disagree.append(f"{act['id']}.{fld['name']}: served {fld['required']}, document says {want}")
	assert disagree == [], f'the endpoint disagrees with its own document: {disagree[:10]}'


async def test_the_requirement_reader_agrees_with_the_route_document() -> None:
	"""The reader the marking is computed from, against a second reader of the same routes.

	This is the gate that would have caught the blind spot the first version of this unit shipped
	with: `required_fields()` tested `param.default is inspect.Parameter.empty`, and a
	`Body(...)`/`Form(...)` marker is not `empty`, so **34 routes'** required parameters were invisible
	to it — and because the marking is computed from that reader, every one of those fields was drawn
	as optional while the route refused without it. The document is generated by FastAPI from the same
	routes by a different path, so a disagreement is a fact about one of the two readers.

	An equality in both directions, not a floor. A parameter this reader calls required and the
	document does not is the mirror defect — a form refusing a submission the server accepts.
	"""
	app = create_app(build_services())
	required = required_fields(app)
	document = _document_required(app)
	assert required and document, 'one of the readers returned nothing, so this would pass vacuously'

	# Only routes the catalogue reaches are compared: the document covers the whole app, and a route
	# no form draws has no marking to be wrong about.
	reached = {(a.method, a.path) for a in catalogue()}
	wrong: dict[str, list[str]] = {}
	for route in sorted(reached & set(document)):
		ours = required.get(route, frozenset())
		theirs = document[route]
		# A path placeholder is collected by both readers, and `authorization` by neither — but the
		# document also carries query parameters the reader sees, so the comparison is on the
		# difference rather than on the whole sets.
		if ours != theirs:
			wrong[f'{route[0]} {route[1]}'] = [
				f'only ours: {sorted(ours - theirs)}', f'only document: {sorted(theirs - ours)}']
	assert wrong == {}, f'routes where the reader and the document disagree: {wrong}'

	marked = sum(1 for a in catalogue() for f in a.fields if f.name in required.get((a.method, a.path), frozenset()))
	assert marked >= 400, f'expected the routes to require many offered fields, saw {marked}'


async def test_a_marked_field_is_one_the_route_refuses_without() -> None:
	"""The equality above is against a *reader* of the routes; this is against the routes themselves.

	`required_fields` is one reading of what a route needs, and a gate that only ever compares the
	served document to that reading cannot see the reader's own blind spot — which is exactly how it
	missed the `Body(...)`/`Form(...)` markers (a marker is not `inspect.Parameter.empty`, so 34
	routes' required params were invisible to it). So for a sample of marked fields, post without the
	field and require a 422 naming it.
	"""
	app = create_app(build_services())
	required = required_fields(app)
	served = _full()
	by_id = {a['id']: a for a in served}

	probed = 0
	missed: list[str] = []
	async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url='http://t') as c:
		for act in served:
			if act['method'] not in ('POST', 'PUT', 'PATCH'):
				continue
			req = required.get((act['method'], act['path']), frozenset())
			marked = {f['name'] for f in act['fields'] if f['required']}
			if not marked:
				continue
			# Post everything required *except* one marked field, and see whether the route minds.
			drop = sorted(marked)[0]
			body = {name: _value_for(by_id[act['id']], name) for name in req if name != drop}
			body.update({f['name']: 'ME' for f in act['fields'] if f.get('client_supplied')})
			path = act['path']
			for seg in path.split('/'):
				if seg.startswith('{'):
					path = path.replace(seg, 'P1')
			probed += 1
			try:
				resp = await c.request(act['method'], path, json=body)
			except Exception:
				# A route that raises on a malformed request is not this gate's subject.
				continue
			if resp.status_code < 400:
				missed.append(f"{act['id']}: dropped {drop!r} and the route accepted it")
	assert probed >= 50, f'expected to probe many routes, probed {probed}'
	# A route may legitimately accept a request without a marked field when the field is a query
	# parameter or a path segment rather than a body property — this gate is about the body, so a
	# small tail is expected and named rather than floored.
	assert len(missed) <= 25, f'fields marked required that the route does not miss: {missed[:12]}'


def _value_for(action: dict, name: str) -> object:
	for f in action['fields']:
		if f['name'] != name:
			continue
		if f['type'] == 'select':
			return (f.get('options') or ['x'])[0]
		if f['type'] == 'list':
			return ['a']
		if f['type'] == 'int':
			return 40
		if f['type'] == 'decimal':
			return 36.5
		if f['type'] == 'bool':
			return True
		if f['type'] == 'path':
			return 'P1'
		return 'a value long enough to pass a minimum'
	return 'a value long enough to pass a minimum'


# The sites where the route's own model refuses a *combination* of answers, and the condition that
# states it. Every one was found by reading the models' `after` validators and asking which of them
# name two fields the form draws; the two that name a field no form draws (`CaseReport.voice_note`,
# `WhatsAppIn.voice_note_lang`) are not here, because a form cannot mislead about a question it does
# not ask. An entry that stops being a condition must come off this list, or it becomes a place to
# hide a new one.
_CONDITIONS = {
	'flag_misinformation': {
		'evidence_consent': ('evidence_ref', []),
	},
	'register_border': {
		'lab_turnaround_hours': ('mobile_lab', ['true']),
		'lab_tests': ('mobile_lab', ['true']),
	},
	# `CaseReport._a_note_is_kept_in_the_language_it_was_said_in` is a **biconditional** — a
	# transcript with no language and a language with no transcript are both refused — so it is
	# carried as two conditions pointing at each other. Both directions are needed: the catalogue had
	# neither, and the model's own comment says the two fields exist so a CHW who dictated an
	# observation need not retype it, which no client could reach.
	'submit_case': {
		'voice_note': ('voice_note_lang', []),
		'voice_note_lang': ('voice_note', []),
	},
}

# Where the route accepts *one of several* answers, which is not a property of any one field: neither
# member is required (the other satisfies the route) and neither is optional (nothing else does). A
# per-field boolean has no third state, so the rule is carried on the action. Marking each member
# required-when-the-other-is-blank would be the mirror of this unit's defect — a form demanding both
# from an empty screen and refusing a submission the route accepts.
_GROUPS = {
	'flag_misinformation': [{'fields': ['evidence_ref', 'transcript'],
	                         'when': 'medium', 'equals_any': ['voice', 'screenshot', 'whatsapp_forward']}],
	'report_suspicious_medicine': [{'fields': ['gtin', 'batch_number'],
	                                'when': None, 'equals_any': []}],
}

# A rule that a field must *differ* from another is not a requiredness condition and cannot be one:
# the answer that fires it is the answer that clears it, so `required = (a != b)` is false whenever
# the person has answered at all. `BackTranslation` refuses a render by the translator, and the
# catalogue says so in prose ("Rendered back by") that a form cannot act on. It is carried as its own
# flag so a client can at least label the pair, and the gate below pins that it is *not* a condition.
_DISTINCT = {'record_back_translation': {'back_translated_by': 'translated_by'}}


async def test_a_conditional_field_states_the_answer_that_makes_it_required() -> None:
	"""The mechanism, against the served document, as an exact key set rather than a floor.

	A floor set at the count it guards can never fail — it passes when one site loses its condition
	and another gains one. This pins which fields carry a condition and what the condition is.
	"""
	served = _full()
	by_id = {a['id']: a for a in served}
	seen: dict[str, dict] = {}
	for act_id in _CONDITIONS:
		assert act_id in by_id, f'{act_id} is no longer served, so its condition is untested'
		got = {}
		for f in by_id[act_id]['fields']:
			cond = f.get('condition')
			if cond is None:
				continue
			got[f['name']] = (cond['when'], cond['equals_any'])
		seen[act_id] = got
	assert seen == _CONDITIONS, f'conditional fields drifted: {seen}'

	# The either/or groups, and the distinctness rule, which are deliberately not conditions.
	groups = {a['id']: a['any_of'] for a in served if a.get('any_of')}
	assert groups == _GROUPS, f'any_of groups drifted: {groups}'
	distinct = {a['id']: {f['name']: f['distinct_from'] for f in a['fields'] if f.get('distinct_from')}
	            for a in served if any(f.get('distinct_from') for f in a['fields'])}
	assert distinct == _DISTINCT, f'distinctness rules drifted: {distinct}'
	assert not [f for a in served for f in a['fields']
	            if f.get('distinct_from') and f.get('condition')], (
		'a field carries both a condition and a distinctness rule; the condition would shadow it')
	# A member of an either/or group must not also be individually conditional or individually
	# required: both would say "answer this" about a field the route accepts an alternative for.
	members = {f"{a['id']}.{n}" for a in served for g in a.get('any_of', []) for n in g['fields']}
	assert members == {'flag_misinformation.evidence_ref', 'flag_misinformation.transcript',
	                   'report_suspicious_medicine.gtin', 'report_suspicious_medicine.batch_number'}, members
	overlap = [f"{a['id']}.{f['name']}" for a in served for f in a['fields']
	           if f"{a['id']}.{f['name']}" in members and (f['required'] or f.get('condition'))]
	assert overlap == [], f'fields in an either/or group that also claim to be individually needed: {overlap}'


async def test_a_field_carrying_a_condition_is_not_also_unconditionally_required() -> None:
	"""A condition on a field the route always requires is a contradiction, and a client that read it
	would drop the asterisk exactly when the answer made the field matter most."""
	served = _full()
	bad = [f"{a['id']}.{f['name']}" for a in served for f in a['fields']
	       if f.get('condition') and f['required']]
	assert bad == [], f'fields both unconditionally required and conditional: {bad}'


async def test_a_route_requires_nothing_its_form_does_not_draw() -> None:
	"""Every required parameter on a catalogue route is a field that route's form draws.

	This is the same defect as the unit's own, one step further out: `required` can only be *marked*
	on a field that exists, so a requirement naming something the form never draws cannot be marked,
	cannot be warned about, and is refused at the front door with the form looking complete. It is the
	`required_fields()` blind spot from the other side — that one lost requirements the form did draw;
	this one finds requirements there is no field for at all.

	`correct_my_data` shipped with `at_iso: str` as a required *query parameter* and no field for it,
	so a person filling the whole form was refused for a missing `at_iso` the form had never asked
	for. The census found it; this gate is what keeps the next one from shipping.
	"""
	app = create_app(build_services())
	required = required_fields(app)
	# `authorization` is the transport's header, not a question; it is never drawn and never should be.
	ignored = {'authorization'}
	undrawn: dict[str, list[str]] = {}
	for act in catalogue():
		need = required.get((act.method, act.path), frozenset()) - ignored
		names = {f.name for f in act.fields}
		missing = sorted(need - names)
		if missing:
			undrawn[f'{act.id} ({act.method} {act.path})'] = missing
	assert undrawn == {}, f'catalogue routes require parameters their form does not draw: {undrawn}'


async def test_the_condition_names_a_field_the_form_actually_draws() -> None:
	"""A condition on a field nobody can answer is a condition the client can never evaluate.

	This is the `voice_note_lang` shape: `CaseReport` refuses a voice note that is also text, and
	neither client draws either field, so the condition is true, unstatable, and harmless — until
	someone adds the field to the form and the catalogue has no condition to show.
	"""
	served = _full()
	broken: dict[str, str] = {}
	for act in served:
		names = {f['name'] for f in act['fields']}
		drawable = {f['name'] for f in act['fields']
		            if not f.get('client_supplied') and not f.get('server_assigned')}
		for f in act['fields']:
			cond = f.get('condition')
			if not cond:
				continue
			if cond['when'] not in names:
				broken[f"{act['id']}.{f['name']}"] = f"names {cond['when']!r}, which the action lacks"
			elif cond['when'] not in drawable:
				broken[f"{act['id']}.{f['name']}"] = f"names {cond['when']!r}, which no form draws"
	assert broken == {}, f'conditions a client cannot evaluate: {broken}'


def _group_open(group: dict, answers: dict[str, str]) -> bool:
	"""Whether an either/or group is currently unsatisfied — the other half of the client's rule.

	The group is *asked* only when its own gate holds, and it is *unsatisfied* when none of its
	members has an answer. A client refuses the submission on exactly that pair, and a server refuses
	it for the same reason one round trip later.
	"""
	if group['when'] is not None:
		given = answers.get(group['when'], '')
		if group['equals_any'] and given not in group['equals_any']:
			return False
		if not group['equals_any'] and given == '':
			return False
	return not any(answers.get(n, '') for n in group['fields'])


def _required_now(field: dict, answers: dict[str, str]) -> bool:
	"""What a client computes: whether this field must be answered, given the answers so far.

	The whole of the mechanism, in one function, because both shipped clients implement exactly this
	and a client that disagrees with the server is the defect this unit exists to close. `when_blank`
	and `equals_any` are mutually exclusive by the model's own contract, so this reads them in the
	order the model guarantees.
	"""
	cond = field.get('condition')
	if field.get('required') or not cond:
		return bool(field.get('required'))
	given = answers.get(cond['when'], '')
	if cond['when_blank']:
		return given == ''
	if cond['equals_any']:
		return given in cond['equals_any']
	# No values named means *any* answer fires it — the `evidence_consent` shape, required exactly
	# when there is a recording to consent to. Spelled out rather than folded into `equals_any`,
	# because an empty list that meant "any" would make a condition with no values silently
	# unsatisfiable on one client and always-satisfied on another.
	return given != ''


def test_the_client_rule_is_the_servers_rule() -> None:
	"""Canary for the predicate above, on the four shapes and their boundaries.

	Driven on constructed fields rather than the live catalogue, because the live catalogue cannot
	produce the "trigger answered with a value that does *not* fire the condition" case for every
	shape — and a branch no input reaches is a branch nobody has watched fail.
	"""
	cond = lambda **kw: {'when': kw.pop('when'), 'equals_any': kw.pop('equals_any', []),
	                     'when_blank': kw.pop('when_blank', False)}
	plain = {'name': 'x', 'required': False, 'condition': None}

	assert not _required_now(plain, {})
	assert _required_now({'name': 'x', 'required': True, 'condition': None}, {})

	enum = {'name': 'evidence_ref', 'required': False,
	        'condition': cond(when='medium', equals_any=['voice', 'screenshot'])}
	assert _required_now(enum, {'medium': 'voice'})
	assert _required_now(enum, {'medium': 'screenshot'})
	# The answer that does *not* fire it — the case a live catalogue cannot always supply.
	assert not _required_now(enum, {'medium': 'text'})
	assert not _required_now(enum, {})

	any_answer = {'name': 'evidence_consent', 'required': False,
	              'condition': cond(when='evidence_ref')}
	assert _required_now(any_answer, {'evidence_ref': 'a photo'})
	assert not _required_now(any_answer, {'evidence_ref': ''})
	assert not _required_now(any_answer, {})

	blank = {'name': 'gtin', 'required': False, 'condition': cond(when='batch_number', when_blank=True)}
	assert _required_now(blank, {'batch_number': ''})
	assert _required_now(blank, {})
	assert not _required_now(blank, {'batch_number': 'B123'})

	# The either/or groups, on all four states: unsatisfied, satisfied by the first member,
	# satisfied by the second, and gated off entirely.
	ungated = {'fields': ['gtin', 'batch_number'], 'when': None, 'equals_any': []}
	assert _group_open(ungated, {})
	assert _group_open(ungated, {'gtin': '', 'batch_number': ''})
	assert not _group_open(ungated, {'gtin': '1234'})
	assert not _group_open(ungated, {'batch_number': 'B1'})

	gated = {'fields': ['evidence_ref', 'transcript'], 'when': 'medium',
	         'equals_any': ['voice', 'screenshot']}
	assert _group_open(gated, {'medium': 'voice'})
	# The gate is closed for a medium that carries no payload — the case the route accepts.
	assert not _group_open(gated, {'medium': 'text'})
	assert not _group_open(gated, {})
	assert not _group_open(gated, {'medium': 'voice', 'transcript': 'it said so'})
	assert not _group_open(gated, {'medium': 'screenshot', 'evidence_ref': 'blob://x'})


async def test_the_route_refuses_exactly_what_the_condition_warns_about() -> None:
	"""The condition and the route's refusal, driven together at the front door.

	The point of the condition is that a form can warn *before* the server refuses. So the two must
	agree: when the condition says a field is required, the route must refuse without it, and when
	the condition says it is not, the route must accept.
	"""
	app = create_app(build_services())
	served = {a['id']: a for a in _full()}
	bad: list[str] = []

	async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url='http://t') as c:
		# The named site, end to end: a voice report with no recording, and with one.
		act = served['flag_misinformation']
		base = {'claim': 'the water is poisoned', 'county': 'Nairobi'}
		without = await c.post('/community/misinformation', json={**base, 'medium': 'voice'})
		if without.status_code != 422:
			bad.append(f'voice with no recording was accepted: {without.status_code}')
		with_evidence = await c.post('/community/misinformation',
		                             json={**base, 'medium': 'voice', 'transcript': 'it said so'})
		if with_evidence.status_code >= 400:
			bad.append(f'voice with a transcript was refused: {with_evidence.text[:120]}')
		as_text = await c.post('/community/misinformation', json={**base, 'medium': 'text'})
		if as_text.status_code >= 400:
			bad.append(f'a text report was refused: {as_text.text[:120]}')

		# And the rule the form would read agrees with all four, including the two the route accepts
		# for the *same* reason — the group is satisfied by either member.
		group = act['any_of'][0]
		assert _group_open(group, {'medium': 'voice'}) is True
		assert _group_open(group, {'medium': 'voice', 'transcript': 'it said so'}) is False
		assert _group_open(group, {'medium': 'screenshot', 'evidence_ref': 'blob://x'}) is False
		assert _group_open(group, {'medium': 'text'}) is False
	assert bad == [], f'the condition and the route disagree: {bad}'


async def test_a_simplified_form_does_not_drop_a_field_a_condition_makes_required() -> None:
	"""§ACC-001's drop list and the new condition, crossed.

	`flag_misinformation` drops `evidence_ref`, `transcript` and `evidence_consent` in simple mode,
	and all three are exactly the fields the medium condition makes required. That is not necessarily
	wrong — a simple form may legitimately ask less — but it must not do it silently: the condition
	has to survive on the fields that remain, or a simple form becomes a form whose submission the
	route refuses with no way for the person to know why.
	"""
	simple = {a['id']: a for a in _simplified()}
	act = simple.get('flag_misinformation')
	assert act is not None, 'flag_misinformation vanished from the simple catalogue'
	drawn = {f['name'] for f in act['fields']}
	kept = {f['name']: f for f in act['fields'] if f.get('condition')}
	# Whatever the drop list keeps, the trigger must still be drawn if any dependent is.
	for name, f in kept.items():
		assert f['condition']['when'] in drawn, (
			f'{name} keeps a condition on {f["condition"]["when"]!r}, which simple mode drops')
	# And the medium question itself must survive, or the person cannot answer the one thing the
	# condition keys off.
	assert 'medium' in drawn, 'simple mode dropped the field every condition on this action names'


# --- The condition has to be evaluable by the client that draws the control -----------------------
#
# The gates above check the catalogue against the route. This one checks it against the *control*:
# a condition a client cannot evaluate is a condition that never fires, and the client's evaluation
# depends on what the field type lets a person leave blank.

def test_a_select_a_condition_keys_off_can_be_left_unanswered() -> None:
	"""A picker always holds a value, so `equals_any=[]` on a select is a condition that is always true.

	This is the unit's own defect one level down: `evidence_consent` is required "whenever there is a
	recording", and `submit_case`'s transcript needs its language — both read as conditional and both
	would behave as `required = True` if the trigger could never be blank. Both clients used to render
	every select as a picker holding its first option, so *every* optional select was silently sent
	with a default the person never chose.

	The predicate is the shape, not the intent: a condition with an empty `equals_any` keyed on a
	select whose route requires it can never fire, because the trigger is always answered.
	"""
	served = _full()
	dead: dict[str, str] = {}
	for act in served:
		kinds = {f['name']: f['type'] for f in act['fields']}
		needed = {f['name'] for f in act['fields'] if f['required']}
		for f in act['fields']:
			c = f.get('condition')
			if c is None or c['equals_any'] or kinds.get(c['when']) != 'select':
				continue
			if c['when'] in needed:
				dead[f"{act['id']}.{f['name']}"] = (
					f"fires on any answer to {c['when']!r}, which the route always requires")
	assert dead == {}, f'conditions that can never fire: {dead}'
	# And the other half: an optional select is one a client can leave blank. Pinned by name rather
	# than counted, because "there are some" is satisfied by the wrong ones.
	optional_selects = {(a['id'], f['name']) for a in served for f in a['fields']
	                    if f['type'] == 'select' and not f['required']}
	assert optional_selects, 'no optional select exists, so the blank-choice rule is untested'


async def test_a_biconditional_is_refused_from_both_sides_and_the_form_warns_on_both() -> None:
	"""`CaseReport`'s note rule, end to end, from the side the form used to be silent about.

	The model refuses a transcript with no language *and* a language with no transcript. A catalogue
	that carried only the first direction would warn about one refusal and present the other as
	complete — the unit's defect surviving on half the rule. So both directions are driven at the
	front door and both are evaluated by the same predicate the clients use.
	"""
	app = create_app(build_services())
	act = {a['id']: a for a in _full()}['submit_case']
	base = {'chw_ref': 'CHW-1', 'county': 'Nairobi', 'community': 'Kibera',
	        'symptoms': ['fever'], 'suspected_disease': 'evd'}
	refusals: list[str] = []
	async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url='http://t') as c:
		# The route is behind the `assigned` scope, so a token is needed for the refusal to be about
		# the model rather than about the transport. A 401 read as "refused" would make this gate pass
		# on a route it never reached.
		verifier = secrets.token_urlsafe(64)[:64]
		authz = (await c.post('/auth/pkce/authorize', json={
			'client_id': 'app', 'redirect_uri': 'afya://cb',
			'code_challenge': s256(verifier), 'state': 'state-1234'})).json()
		tok = (await c.post('/auth/pkce/token', params={'role': 'chw'}, json={
			'authorization_code': authz['authorization_code'], 'client_id': 'app',
			'redirect_uri': 'afya://cb', 'code_verifier': verifier})).json()['access_token']
		h = {'Authorization': f'Bearer {tok}', 'x-device-id': 'biconditional-probe'}
		for label, extra, expect_refused in [
			('neither field', {}, False),
			('transcript only', {'voice_note': 'the child has a fever'}, True),
			('language only', {'voice_note_lang': 'sw'}, True),
			('both', {'voice_note': 'the child has a fever', 'voice_note_lang': 'sw'}, False),
		]:
			r = await c.post('/community/cases', json={**base, **extra}, headers=h)
			assert r.status_code != 401, f'{label}: the probe never reached the model'
			refused = r.status_code == 422
			if refused != expect_refused:
				refusals.append(f'{label}: route said {r.status_code}, expected '
				                f'{"422" if expect_refused else "accepted"} — {r.text[:110]}')
	assert refusals == [], f'the route disagrees with the rule the form states: {refusals}'

	# And the form's own reading of the same four answers, through the predicate the clients share.
	conditions = {f['name']: f.get('condition') for f in act['fields']}
	forms = {'voice_note': conditions.get('voice_note'), 'voice_note_lang': conditions.get('voice_note_lang')}
	assert forms['voice_note'] and forms['voice_note_lang'], (
		'submit_case lost a direction of the biconditional, so a client warns on one side only')
	for name, cond in forms.items():
		assert cond is not None, f'{name} carries no condition'
		assert cond['when'] in conditions, f'{name} keys on a field the form does not draw'


# --- The third rule the catalogue carries and no client read --------------------------------------
#
# `distinct_from` is not requiredness and is not a condition — `required = (a != b)` is false for
# every answer — so it lives on its own flag. Both clients parsed it and neither read it, so the one
# action carrying it offered a submission the route refuses with nothing on the form to warn about.

def test_a_distinctness_rule_is_carried_on_exactly_the_fields_the_route_enforces() -> None:
	"""`distinct_from` must name a field the form draws, on the action whose route refuses it.

	`BackTranslation` raises when the renderer is the translator: the method needs someone who has not
	seen the source, so a record naming one person twice is a false statement about who checked what.
	The catalogue states it and the clients now act on it. What this pins is that the *carried* rule
	still matches the route's, in both directions — a flag pointing at a field the action lacks is
	unevaluable, and a route rule with no flag is a refusal the form cannot warn about.
	"""
	served = {a['id']: a for a in _full()}
	carried = {(a['id'], f['name']): f['distinct_from'] for a in served.values() for f in a['fields']
	           if f.get('distinct_from')}
	assert carried == {('record_back_translation', 'back_translated_by'): 'translated_by'}, carried
	# The field it names is drawn, so a client can compare two answers it actually holds.
	act = served['record_back_translation']
	drawn = {f['name'] for f in act['fields']
	         if not f.get('client_supplied') and not f.get('server_assigned')}
	for (_, name), other in carried.items():
		assert other in drawn, f'{name} must differ from {other!r}, which the form does not draw'
		assert name in drawn, f'{name} is not drawn, so the rule cannot be evaluated'


async def test_the_distinctness_rule_is_the_routes_refusal() -> None:
	"""The same rule, driven at the front door: equal names are refused, different ones accepted.

	Both clients now refuse before the request, which is only honest if the route refuses after it for
	the same reason. A route that accepted the pair would make the form stricter than the server; a
	route that refused for another reason would make the form's message wrong.
	"""
	from afya.privacy.views import RBACRole
	from afya.service import build_services as _build

	services = _build()
	from afya.auth.service import AuthService
	auth: AuthService = services['auth']  # type: ignore[assignment]
	ops = auth.provision_staff('distinct-0', RBACRole.sysadmin, registrar='MoH ops').access_token
	h = {'authorization': f'Bearer {ops}'}
	app = create_app(services)
	body = {'item_id': 'INF-003-sw', 'back_translation': 'rendered back'}

	async with httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url='http://t') as c:
		same = await c.post('/info/content/back-translation',
		                    json={**body, 'translated_by': 'A', 'back_translated_by': 'A'}, headers=h)
		assert same.status_code == 422, f'the route accepted a render by the translator: {same.text[:120]}'
		assert 'not a back-translation' in same.text, (
			f'the refusal does not name the rule the form states: {same.text[:160]}')
		apart = await c.post('/info/content/back-translation',
		                     json={**body, 'translated_by': 'A', 'back_translated_by': 'B'}, headers=h)
		assert apart.status_code == 200, apart.text[:160]


def test_both_clients_read_the_distinctness_flag() -> None:
	"""A flag both clients *parsed* and neither *read* is a field written and never used.

	`ActionField.distinctFrom` and `MobileFieldDTO.distinct_from` were decoded on both platforms and
	referenced nowhere else — the defect the repo has met before, a model field whose declaration,
	construction and serialiser are its only reads. The check is on the read, not the declaration: a
	client that decodes the flag and compares nothing satisfies `'distinct_from' in src`.
	"""
	import pathlib
	root = pathlib.Path(__file__).resolve().parents[2]
	kotlin = (root / 'android/app/src/main/java/ke/go/health/afyayangu/ActionsActivity.kt').read_text()
	assert 'val other = f.distinctFrom ?: return@filter false' in kotlin, \
		'Android decodes distinctFrom and never compares it'
	assert 'mine == answers[other]' in kotlin, 'Android reads the flag without using the answer'
	swift = (root / 'ios/AfyaYangu/Features.swift').read_text()
	assert 'guard let other = f.distinct_from else { return false }' in swift, \
		'iOS decodes distinct_from and never compares it'
	assert 'mine == values[other]' in swift, 'iOS reads the flag without using the answer'
