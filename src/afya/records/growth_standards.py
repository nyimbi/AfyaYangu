"""WHO Child Growth Standards — the LMS parameters §REC-003's percentile charts compute from.

`growth_flag` in `afya.records.service` compares a measurement against a hard-coded band: a table of
low/high weights and median heights per age, typed into the function. A band is not a standard. It
cannot say *how far* below, it has no resolution between the six ages someone chose, and it traces to
no published table — so "your child is underweight" is a verdict whose number nobody can check.

The WHO Child Growth Standards publish, for every month of age, three parameters per sex: the Box-Cox
power `L`, the median `M`, and the coefficient of variation `S`. The z-score of a measurement is then

    z = ((x / M) ** L - 1) / (L * S)        for L != 0
    z = ln(x / M) / S                       for L == 0

which is exact at every tabulated month and needs no interpolation. This module holds those
parameters verbatim; `afya.records.growth` computes with them.

The source PDFs are archived in `sources/who-child-growth-standards/` with checksums and retrieval
URLs in `sources/INDEX.md`. The numbers are reproduced here rather than read at runtime: the
deployment has no xlsx reader, no network egress is wanted inside a clinical calculation, and a
growth standard that can silently change under a running service is not a standard.

Coverage is 0-60 months. Length-for-age and height-for-age are split at 24 months the way WHO
publishes them — recumbent length below two years, standing height at and above — because the two
measurements differ by about 0.7 cm and a single table would mix two scales.
"""



